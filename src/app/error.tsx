"use client";

import React, { useEffect } from "react";
import { useRouter } from "next/navigation";

export default function ErrorBoundary({
  error,
  reset,
}: {
  error: Error & { digest?: string };
  reset: () => void;
}) {
  const router = useRouter();

  useEffect(() => {
    console.error("Platform boundary caught runtime fault:", error);
    
    const systemLogs = `[SYSTEM_PANIC] SEGMENT FAULT ENCOUNTERED\n` +
      `TIMESTAMP: ${new Date().toISOString()}\n` +
      `FAULT_MSG: ${error.message || "UNIDENTIFIED INTERNAL METADATA ERROR"}\n` +
      `DIGEST_ID: ${error.digest || "N/A"}\n\n` +
      `STACK_TRACE_LOG:\n${error.stack || "No stack trace generated by agent."}`;

    router.push(`/error-terminal?log=${encodeURIComponent(systemLogs)}`);
  }, [error, router]);

  return (
    <div className="bg-[#0A0A0A] text-[#e5e2e1] font-body-mono min-h-screen flex items-center justify-center p-6">
      <div className="text-center space-y-4 max-w-md p-8 bg-[#0e0e0e] border border-[#93000c] rounded-sm shadow-[0_0_30px_rgba(147,0,12,0.3)]">
        <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-error mx-auto mb-2"></div>
        <h2 className="font-display-tech text-xs text-error tracking-widest uppercase">[ CRITICAL_SYSTEM_FAULT ]</h2>
        <p className="font-body-mono-sm text-[10px] text-[#b9ccb2]">
          Redirecting interface to isolated manual replication console...
        </p>
      </div>
    </div>
  );
}
